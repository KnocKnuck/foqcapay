@router.get("/stats")
async def get_signal_statistics(
    pair: Optional[str] = None,
    days: int = Query(7, ge=1, le=90),
):
    """
    Get signal statistics.

    Args:
        pair: Filter by trading pair
        days: Number of days to analyze

    Returns:
        Signal statistics and counts
    """
    try:
        # Calculate start date
        start_date = datetime.utcnow() - timedelta(days=days)

        signals = list(_signal_history.values())

        # Filter by pair
        if pair:
            signals = [s for s in signals if s.get("pair") == pair]

        # Filter by date
        signals = [
            s for s in signals
            if datetime.fromisoformat(s.get("timestamp", "").replace("Z", "+00:00")) >= start_date
        ]

        # Calculate statistics
        stats_by_indicator = defaultdict(lambda: {"count": 0, "avg_strength": 0, "signals": []})
        stats_by_type = defaultdict(int)
        stats_by_pair = defaultdict(int)

        total_strength = 0
        for signal in signals:
            indicator = signal.get("indicator", "UNKNOWN")
            signal_type = signal.get("signal_type", "unknown")
            signal_pair = signal.get("pair", "unknown")
            strength = signal.get("strength", 0)

            stats_by_indicator[indicator]["count"] += 1
            stats_by_indicator[indicator]["signals"].append(signal_type)
            total_strength += strength

            stats_by_type[signal_type] += 1
            stats_by_pair[signal_pair] += 1

        # Calculate average strength per indicator
        for indicator, data in stats_by_indicator.items():
            indicator_signals = [s for s in signals if s.get("indicator") == indicator]
            if indicator_signals:
                avg_strength = sum(s.get("strength", 0) for s in indicator_signals) / len(indicator_signals)
                stats_by_indicator[indicator]["avg_strength"] = round(avg_strength, 2)

        avg_strength = round(total_strength / len(signals), 2) if signals else 0

        return {
            "success": True,
            "period_days": days,
            "total_signals": len(signals),
            "avg_strength": avg_strength,
            "by_indicator": dict(stats_by_indicator),
            "by_type": dict(stats_by_type),
            "by_pair": dict(stats_by_pair),
            "start_date": start_date.isoformat(),
            "end_date": datetime.utcnow().isoformat(),
        }

    except Exception as e:
        logger.error("Failed to get signal statistics", error=str(e))
        raise HTTPException(status_code=500, detail=str(e))


