@router.post("/record")
async def record_signal(signal: Dict[str, Any]):
    """
    Record a new signal (called by indicator agents via event bus).

    Args:
        signal: Signal data

    Returns:
        Success confirmation
    """
    try:
        signal_id = f"{signal.get('pair', 'unknown')}-{signal.get('timestamp', datetime.utcnow().isoformat())}-{hash(str(signal))}"

        _signal_history[signal_id] = {
            "signal_id": signal_id,
            **signal
        }

        # Update counts
        indicator = signal.get("indicator", "UNKNOWN")
        _signal_counts[indicator] += 1

        logger.info(
            "Signal recorded",
            signal_id=signal_id,
            indicator=indicator,
            pair=signal.get("pair"),
            signal_type=signal.get("signal_type")
        )

        return {
            "success": True,
            "signal_id": signal_id,
        }

    except Exception as e:
        logger.error("Failed to record signal", error=str(e))
        raise HTTPException(status_code=500, detail=str(e))


