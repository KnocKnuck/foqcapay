logger = structlog.get_logger(__name__)

router = APIRouter(prefix="/signals", tags=["signals"])

# In-memory signal storage (in production, use database)
# {signal_id: signal_data}
_signal_history: Dict[str, Dict[str, Any]] = {}

# Signal counts by type
_signal_counts: Dict[str, int] = defaultdict(int)


@router.get("/history")
async def get_signal_history(
    pair: Optional[str] = None,
    indicator: Optional[str] = Query(None, description="MA, RSI, MACD, BB, VOLUME"),
    signal_type: Optional[str] = None,
    start_date: Optional[str] = None,
    end_date: Optional[str] = None,
    limit: int = Query(100, le=500),
    offset: int = 0,
):
    """
    Get signal history with filtering.

    Args:
        pair: Filter by trading pair (e.g., 'BTC/USDC')
        indicator: Filter by indicator type
        signal_type: Filter by signal type (e.g., 'golden_cross', 'overbought')
        start_date: Start date (ISO format)
        end_date: End date (ISO format)
        limit: Maximum number of results
        offset: Offset for pagination

    Returns:
        Signal history with metadata
    """
    try:
        # Get all signals
        signals = list(_signal_history.values())

        # Apply filters
        if pair:
            signals = [s for s in signals if s.get("pair") == pair]

        if indicator:
            signals = [s for s in signals if s.get("indicator") == indicator.upper()]

        if signal_type:
            signals = [s for s in signals if s.get("signal_type") == signal_type]

        # Date filtering
        if start_date:
            start_dt = datetime.fromisoformat(start_date.replace("Z", "+00:00"))
            signals = [
                s for s in signals
                if datetime.fromisoformat(s.get("timestamp", "").replace("Z", "+00:00")) >= start_dt
            ]

        if end_date:
            end_dt = datetime.fromisoformat(end_date.replace("Z", "+00:00"))
            signals = [
                s for s in signals
                if datetime.fromisoformat(s.get("timestamp", "").replace("Z", "+00:00")) <= end_dt
            ]

        # Sort by timestamp (newest first)
        signals.sort(
            key=lambda x: datetime.fromisoformat(x.get("timestamp", "").replace("Z", "+00:00")),
            reverse=True
        )

        # Pagination
        total_count = len(signals)
        signals = signals[offset: offset + limit]

        return {
            "success": True,
            "signals": signals,
            "total_count": total_count,
            "limit": limit,
            "offset": offset,
            "filters": {
                "pair": pair,
                "indicator": indicator,
                "signal_type": signal_type,
                "start_date": start_date,
                "end_date": end_date,
            }
        }

    except Exception as e:
        logger.error("Failed to get signal history", error=str(e))
        raise HTTPException(status_code=500, detail=str(e))


