# Utility function to add signal (can be called by agents)
def add_signal(signal_data: Dict[str, Any]) -> str:
    """
    Add a signal to history.

    Args:
        signal_data: Signal data dictionary

    Returns:
        Signal ID
    """
    signal_id = f"{signal_data.get('pair', 'unknown')}-{signal_data.get('timestamp', datetime.utcnow().isoformat())}-{hash(str(signal_data))}"

    _signal_history[signal_id] = {
        "signal_id": signal_id,
        **signal_data
    }

    # Update counts
    indicator = signal_data.get("indicator", "UNKNOWN")
    _signal_counts[indicator] += 1

    return signal_id
